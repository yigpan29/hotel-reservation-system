-- No backfill: only new application events opt a reservation into HU-05.
CREATE TABLE reservation_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    reservation_id bigint NOT NULL REFERENCES reservations(id),
    type varchar(32) NOT NULL CHECK (type IN ('CONFIRMED','CANCELLED','CHECK_IN_REMINDER')),
    hotel_name varchar(255) NOT NULL,
    start_date date NOT NULL,
    end_date date,
    message varchar(1000) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    read_at timestamp with time zone,
    UNIQUE(reservation_id,type),
    CHECK (read_at IS NULL OR read_at>=created_at),
    CHECK (type='CANCELLED' OR (end_date IS NOT NULL AND end_date>start_date))
);
CREATE INDEX notifications_user_recent ON reservation_notifications(user_id,created_at DESC,id DESC);
CREATE INDEX notifications_user_unread ON reservation_notifications(user_id) WHERE read_at IS NULL;
