import { test, expect, type Page } from '/work/node_modules/@playwright/test/index.mjs'

async function login(page: Page, user = 'demo-admin', password = 'Synthetic-admin-123') {
  await page.goto('/login')
  await page.getByLabel('Usuario', { exact: true }).fill(user)
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('heading', { name: 'Mis reservas' })).toBeVisible()
}
async function openDemand(page: Page) {
  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Previsión de demanda', exact: true }).click()
  await expect(page.getByText('Cargando análisis de demanda…')).toHaveCount(0)
}
