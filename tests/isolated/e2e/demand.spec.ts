test('HU03: móvil, errores HTTP y sesión expirada conservan el resto del panel', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page); await openDemand(page)
  await expect(page.getByRole('figure', { name: 'Gráfico de demanda histórica' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('hu03-mobile.png'), fullPage: true })
  await page.route('**/api/admin/demand/**', route => route.abort('failed'))
  await page.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo conectar con el backend')
  await page.unroute('**/api/admin/demand/**')
  await page.route('**/api/admin/demand/**', route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"message":"Fallo de consulta sintético"}' }))
  await page.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(page.getByRole('alert')).toContainText('Fallo de consulta sintético')
  await page.getByRole('tab', { name: 'Hoteles', exact: true }).click()
  await expect(page.getByRole('form', { name: 'Formulario de hotel' })).toBeVisible()
  await page.unroute('**/api/admin/demand/**')
  await page.route('**/api/admin/demand/**', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{"message":"Synthetic expired session"}' }))
  await page.getByRole('tab', { name: 'Previsión de demanda', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('La sesión ha expirado')
  await expect(page.getByRole('link', { name: 'Volver a iniciar sesión' })).toBeVisible()
  expect(errors).toEqual([])
})

test('HU03: USER no puede consultar gráficos ni endpoints administrativos', async ({ page }) => {
  await login(page, 'demo-user', 'Synthetic-user-123')
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'Acceso denegado' })).toBeVisible()
  const responses = await page.evaluate(async () => Promise.all(['/api/admin/demand/history', '/api/admin/demand/forecast'].map(async path => (await fetch(path)).status)))
  expect(responses).toEqual([403, 403])
})
